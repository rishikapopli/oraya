import { useEffect, useRef, useState } from "react";
import { ArrowUp, Loader2 } from "lucide-react";
import { api } from "../lib/api";
import { Markdown } from "./ui";

const QUESTIONS = [
  "What is a polymer?",
  "What stops the chain?",
  "Give me a real example",
];
const timestamp = (seconds) =>
  `${Math.floor(seconds / 60)}:${String(Math.floor(seconds % 60)).padStart(2, "0")}`;

export function LandingTutor({ onSource }) {
  const [messages, setMessages] = useState([]);
  const [input, setInput] = useState("");
  const [sending, setSending] = useState(false);
  const [error, setError] = useState("");
  const controller = useRef(null);
  const viewport = useRef(null);
  const busy = useRef(false);

  useEffect(() => () => controller.current?.abort(), []);
  useEffect(() => {
    viewport.current?.scrollTo({ top: viewport.current.scrollHeight });
  }, [messages, sending, error]);

  const ask = async (value) => {
    const question = (value ?? input).trim();
    if (!question || busy.current) return;
    busy.current = true;
    setSending(true);
    setError("");
    setInput("");
    const id = `question-${Date.now()}`;
    setMessages((items) => [...items, { id, role: "user", content: question }]);
    controller.current = new AbortController();
    try {
      const data = await api.post(
        "/ai/preview",
        {
          question,
          history: messages
            .slice(-6)
            .map(({ role, content }) => ({ role, content })),
        },
        controller.current.signal,
      );
      setMessages((items) => [
        ...items,
        {
          id: `answer-${Date.now()}`,
          role: "assistant",
          content: data.answer,
          references: data.references,
        },
      ]);
    } catch (err) {
      if (err.name !== "AbortError") {
        setError(err.message);
        setInput(question);
        setMessages((items) => items.filter((message) => message.id !== id));
      }
    } finally {
      busy.current = false;
      setSending(false);
    }
  };

  return (
    <div className="chat live-tutor">
      <div className="live-tutor-label">
        <span aria-hidden="true" /> Live AI · sample polymer lesson
      </div>
      <div
        className="msgs"
        ref={viewport}
        role="log"
        aria-live="polite"
        aria-label="Sample tutor conversation"
      >
        {messages.length === 0 && (
          <div className="m o">
            Ask me about monomers, polymer chains, or how a growing chain stops.
            My answers use the sample lesson on the left.
          </div>
        )}
        {messages.map((message) => (
          <div
            className={`m ${message.role === "user" ? "u" : "o"}`}
            key={message.id}
          >
            {message.role === "user" ? (
              <p>{message.content}</p>
            ) : (
              <>
                <Markdown text={message.content} />
                {message.references?.length > 0 && (
                  <div
                    className="live-tutor-sources"
                    aria-label="Sample transcript sources"
                  >
                    {message.references.map((reference) => (
                      <button
                        className="ts"
                        type="button"
                        key={reference.start}
                        onClick={() => onSource(reference)}
                        aria-label={`Show sample transcript at ${timestamp(reference.start)}`}
                      >
                        {timestamp(reference.start)}
                      </button>
                    ))}
                  </div>
                )}
                <p className="live-tutor-origin">
                  Generated by AI from the sample transcript
                </p>
              </>
            )}
          </div>
        ))}
        {sending && (
          <div className="m o live-tutor-thinking" role="status">
            <Loader2 size={16} className="animate-spin" aria-hidden="true" />
            Reading the sample transcript…
          </div>
        )}
      </div>
      {error && (
        <p className="live-tutor-error" role="alert">
          {error}
        </p>
      )}
      {messages.length < 3 && (
        <div className="chips">
          {QUESTIONS.map((question) => (
            <button
              type="button"
              key={question}
              disabled={sending}
              onClick={() => ask(question)}
            >
              {question}
            </button>
          ))}
        </div>
      )}
      <form
        className="live-tutor-form"
        onSubmit={(event) => {
          event.preventDefault();
          ask();
        }}
      >
        <label className="sr-only" htmlFor="sample-tutor-question">
          Ask the sample tutor
        </label>
        <input
          id="sample-tutor-question"
          maxLength={500}
          value={input}
          onChange={(event) => setInput(event.target.value)}
          placeholder="Ask about the sample lesson…"
          autoComplete="off"
        />
        <button
          type="submit"
          disabled={sending || !input.trim()}
          aria-label="Send sample question"
        >
          <ArrowUp size={20} aria-hidden="true" />
        </button>
      </form>
    </div>
  );
}
